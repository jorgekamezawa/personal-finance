#!/bin/bash
# Picks machine type and city from the real stock and writes machine.auto.tfvars.
#
# Asking first beats trying: an apply that fails for lack of stock leaves resources half
# created and does not say which alternative would have worked.
set -euo pipefail

: "${HCLOUD_TOKEN:?set HCLOUD_TOKEN}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

CHOICE="$(python3 - <<'PY'
import json, os, sys, urllib.request

# Cheapest first; within a type, changing city costs nothing.
TYPES = ["cx23", "cx33", "cpx12", "cpx22"]
CITIES = ["fsn1", "nbg1", "hel1"]

request = urllib.request.Request(
    "https://api.hetzner.cloud/v1/server_types?per_page=100",
    headers={"Authorization": f"Bearer {os.environ['HCLOUD_TOKEN']}"},
)
with urllib.request.urlopen(request, timeout=30) as response:
    server_types = json.load(response)["server_types"]

available = {
    (server_type["name"], location["name"])
    for server_type in server_types
    for location in server_type.get("locations", [])
    if location.get("available")
}

for server_type in TYPES:
    for city in CITIES:
        if (server_type, city) in available:
            print(f"{server_type}\t{city}")
            sys.exit(0)

print("error: nothing on the ladder is in stock.", file=sys.stderr)
for city in CITIES:
    in_stock = sorted(name for name, where in available if where == city)
    print(f"  {city}: {', '.join(in_stock) or '(nothing)'}", file=sys.stderr)
sys.exit(1)
PY
)"

IFS=$'\t' read -r SERVER_TYPE LOCATION <<< "$CHOICE"

cat > "$HERE/machine.auto.tfvars" <<TFVARS
# Generated by choose-machine.sh. Do not edit: run the script again.
server_type = "$SERVER_TYPE"
location    = "$LOCATION"
TFVARS

echo "==> $SERVER_TYPE @ $LOCATION"
